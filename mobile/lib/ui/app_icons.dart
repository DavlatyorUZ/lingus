class AppIcon extends StatelessWidget {
  final String asset;
  final double? size;
  final Color? color;
  const AppIcon(this.asset, {super.key, this.size, this.color});
  @override
  Widget build(BuildContext c) {
    final t = IconTheme.of(c);
    final tint = color ?? t.color ?? Theme.of(c).colorScheme.onSurface;
    return Center(
      widthFactor: 1,
      heightFactor: 1,
      child: SvgPicture.asset(
        asset,
        width: size ?? t.size ?? 24,
        height: size ?? t.size ?? 24,
        excludeFromSemantics: true,
        colorFilter: ColorFilter.mode(
          tint.withValues(alpha: tint.a * (t.opacity ?? 1)),
          BlendMode.srcIn,
        ),
      ),
    );
  }
}

