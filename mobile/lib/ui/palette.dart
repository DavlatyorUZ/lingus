import 'package:material_ui/material_ui.dart';

@immutable
class LingoyPalette extends ThemeExtension<LingoyPalette> {
  final Color bg,
      surface,
      elevated,
      border,
      brand,
      brandHover,
      brandSoft,
      brandLight,
      cta,
      ctaHover,
      ctaPressed,
      onCta,
      accent,
      text,
      textMuted,
      textDisabled,
      success,
      error,
      warning,
      info,
      bgTop;
  const LingoyPalette({
    required this.bg,
    required this.surface,
    required this.elevated,
    required this.border,
    required this.brand,
    required this.brandHover,
    required this.brandSoft,
    required this.brandLight,
    required this.cta,
    required this.ctaHover,
    required this.ctaPressed,
    required this.onCta,
    required this.accent,
    required this.text,
    required this.textMuted,
    required this.textDisabled,
    required this.success,
    required this.error,
    required this.warning,
    required this.info,
    required this.bgTop,
  });
  static const night = LingoyPalette(
    bg: Color(0xFF100E15),
    surface: Color(0xFF201D29),
    elevated: Color(0xFF2B2635),
    border: Color(0xFF48404F),
    brand: Color(0xFF6A2FC8),
    brandHover: Color(0xFF7B42DB),
    brandSoft: Color(0xFF9D71E8),
    brandLight: Color(0xFFD1B8FF),
    cta: Color(0xFFFFC94D),
    ctaHover: Color(0xFFFFD66E),
    ctaPressed: Color(0xFFE8B038),
    onCta: Color(0xFF0B0720),
    accent: Color(0xFFFF7BAC),
    text: Color(0xFFF5F1EA),
    textMuted: Color(0xFFBDB5C5),
    textDisabled: Color(0xFF6E5FA3),
    success: Color(0xFF5EE2A0),
    error: Color(0xFFFF6B6B),
    warning: Color(0xFFFFB020),
    info: Color(0xFF7FB5FF),
    bgTop: Color(0xFF1C1824),
  );
  static const day = LingoyPalette(
    bg: Color(0xFFFAF8F5),
    surface: Color(0xFFFFFFFF),
    elevated: Color(0xFFF2EEF7),
    border: Color(0xFFE8E2EB),
    brand: Color(0xFF6A2FC8),
    brandHover: Color(0xFF7B42DB),
    brandSoft: Color(0xFF9D71E8),
    brandLight: Color(0xFFD1B8FF),
    cta: Color(0xFFFFC94D),
    ctaHover: Color(0xFFFFD66E),
    ctaPressed: Color(0xFFE8B038),
    onCta: Color(0xFF0B0720),
    accent: Color(0xFFFF7BAC),
    text: Color(0xFF0B0720),
    textMuted: Color(0xFF62606F),
    textDisabled: Color(0xFFA897C7),
    success: Color(0xFF137B4B),
    error: Color(0xFFBD2E46),
    warning: Color(0xFF946000),
    info: Color(0xFF315BA8),
    bgTop: Color(0xFFFAF8F5),
  );
  LinearGradient get background => LinearGradient(
    begin: Alignment.topCenter,
    end: Alignment.bottomCenter,
    colors: [bgTop, bg],
  );
  LinearGradient get brandGradient => LinearGradient(
    begin: Alignment.topLeft,
    end: Alignment.bottomRight,
    colors: [brand, brandSoft],
  );
  @override
  LingoyPalette copyWith({
    Color? bg,
    Color? surface,
    Color? elevated,
    Color? border,
    Color? brand,
    Color? brandHover,
    Color? brandSoft,
    Color? brandLight,
    Color? cta,
    Color? ctaHover,
    Color? ctaPressed,
    Color? onCta,
    Color? accent,
    Color? text,
    Color? textMuted,
    Color? textDisabled,
    Color? success,
    Color? error,
    Color? warning,
    Color? info,
    Color? bgTop,
  }) => LingoyPalette(
    bg: bg ?? this.bg,
    surface: surface ?? this.surface,
    elevated: elevated ?? this.elevated,
    border: border ?? this.border,
    brand: brand ?? this.brand,
    brandHover: brandHover ?? this.brandHover,
    brandSoft: brandSoft ?? this.brandSoft,
    brandLight: brandLight ?? this.brandLight,
    cta: cta ?? this.cta,
    ctaHover: ctaHover ?? this.ctaHover,
    ctaPressed: ctaPressed ?? this.ctaPressed,
    onCta: onCta ?? this.onCta,
    accent: accent ?? this.accent,
    text: text ?? this.text,
    textMuted: textMuted ?? this.textMuted,
    textDisabled: textDisabled ?? this.textDisabled,
    success: success ?? this.success,
    error: error ?? this.error,
    warning: warning ?? this.warning,
    info: info ?? this.info,
    bgTop: bgTop ?? this.bgTop,
  );
  @override
  LingoyPalette lerp(covariant LingoyPalette? other, double t) {
    if (other == null) return this;
    return LingoyPalette(
      bg: Color.lerp(bg, other.bg, t)!,
      surface: Color.lerp(surface, other.surface, t)!,
      elevated: Color.lerp(elevated, other.elevated, t)!,
      border: Color.lerp(border, other.border, t)!,
      brand: Color.lerp(brand, other.brand, t)!,
      brandHover: Color.lerp(brandHover, other.brandHover, t)!,
      brandSoft: Color.lerp(brandSoft, other.brandSoft, t)!,
      brandLight: Color.lerp(brandLight, other.brandLight, t)!,
      cta: Color.lerp(cta, other.cta, t)!,
      ctaHover: Color.lerp(ctaHover, other.ctaHover, t)!,
      ctaPressed: Color.lerp(ctaPressed, other.ctaPressed, t)!,
      onCta: Color.lerp(onCta, other.onCta, t)!,
      accent: Color.lerp(accent, other.accent, t)!,
      text: Color.lerp(text, other.text, t)!,
      textMuted: Color.lerp(textMuted, other.textMuted, t)!,
      textDisabled: Color.lerp(textDisabled, other.textDisabled, t)!,
      success: Color.lerp(success, other.success, t)!,
      error: Color.lerp(error, other.error, t)!,
      warning: Color.lerp(warning, other.warning, t)!,
      info: Color.lerp(info, other.info, t)!,
      bgTop: Color.lerp(bgTop, other.bgTop, t)!,
    );
  }
}

LingoyPalette palette(BuildContext c) =>
    Theme.of(c).extension<LingoyPalette>()!;
